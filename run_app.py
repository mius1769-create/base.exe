"""
Точка входа для PyInstaller-сборки и для запуска `python run_app.py` из корня проекта.

Модуль app/main.py использует относительные импорты (`from . import db`), которые
не работают, если PyInstaller/Python запускает его напрямую как __main__ —
в этом случае Python не знает, что main.py является частью пакета `app`.
Этот файл лежит ВНЕ пакета app и импортирует его как обычный модуль, поэтому
относительные импорты внутри app/ разрешаются корректно.
"""
import sys

from app.main import main

if __name__ == "__main__":
    sys.exit(main())
